// Embed every file in public/ into src/_static.js so the Worker can serve it
// without the static-assets upload API.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = new URL('../public/', import.meta.url).pathname;
const types = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.svg': 'image/svg+xml',
  '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png',
  '.webp': 'image/webp', '.ico': 'image/x-icon', '.json': 'application/json',
};
const files = {};
const walk = dir => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files['/' + relative(root, full)] = {
      type: types[extname(name).toLowerCase()] || 'application/octet-stream',
      body: readFileSync(full).toString('base64'),
    };
  }
};
walk(root);
writeFileSync(new URL('../src/_static.js', import.meta.url),
  '// Generated by scripts/build-static.mjs. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
console.log(`Embedded ${Object.keys(files).length} files`);
